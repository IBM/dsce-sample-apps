"""
B5 — Motivation Nudge App (thin, implementation-agnostic)
==========================================================
Produces a seller-facing motivation/nudge from unified signals pulled
from the lakehouse (Cassandra live + Iceberg history + Databricks federated).

"Motivation Graph" is a conceptual/brand name only.
No graph database, no networkx, no graph structure. (Spec §A7, §B5, §10, §12.)

Design requirement (§B5):
  The nudge must visibly depend on ≥3 unified sources so the data-integration
  value is legible on screen:
    source_1: Salesforce CDC  (live deal pipeline — Cassandra/Iceberg via B2)
    source_2: Slack Events    (live recognition — Cassandra/Iceberg via B2)
    source_3: Databricks Delta (historical seller metric — query-in-place via B4)

Acceptance (§B5): renders a nudge for one seller derived from ≥3 unified sources.
No graph library required.

Act 3 — AI layer (wx.ai):
  headline and body are generated by IBM watsonx.ai (Granite).
  When the LLM is reachable, _apply_rules() sets framing/fallback text and
  _enrich_with_watsonx_ai() replaces headline + body with LLM output.
  The response is annotated with ai_generated=True and ai_ metadata fields
  so the UI can display an explicit "wx.ai" attribution badge.
  On any LLM failure the SQL-rule strings are preserved (graceful fallback).
"""

