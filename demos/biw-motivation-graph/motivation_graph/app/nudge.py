# ── Prompt template ───────────────────────────────────────────────────────────

_NUDGE_PROMPT = """\
You are a motivational coach for enterprise sales teams. Write a short, energizing nudge for a seller.

Seller: {name}
Persona: {persona}
Closed deals (live, Salesforce CDC): {sf_deals}
CRM updates logged (live, Salesforce CDC): {sf_updates}
Peer recognitions received (Slack Events): {recognitions}
Deals closed in last 90 days (Databricks historical): {db_velocity}
Nudge theme: {framing}

Rules:
- headline: one punchy sentence, ≤12 words, personalised with the seller name. No quotation marks.
- body: two to three sentences. Reference the actual numbers above. End with a forward-looking call to action. No quotation marks.
- Output ONLY a single JSON object. No explanation, no markdown, no code fences, no extra text before or after.
- Use exactly these two keys: "headline" and "body".

JSON output:
{{"headline": "...", "body": "..."}}"""


# ── Signal extraction ─────────────────────────────────────────────────────────

def _extract_signals_from_session(con, seller_id: str) -> dict:
    """
    Pull the three required unified-source signals via SQL.
    Works against any DB-API 2.0 connection (Trino / watsonx.data Presto or
    local DuckDB for test/dev).
    """
    def q(sql, params=None):
        cur = con.cursor() if hasattr(con, "cursor") else con
        if params:
            cur.execute(sql, params)
        else:
            cur.execute(sql)
        return cur.fetchone()

    def qn(sql, params=None):
        row = q(sql, params)
        return row[0] if row else 0

    # Source 1: Salesforce CDC — CRM compliance and closed deals
    sf_deals = qn(
        "SELECT COUNT(*) FROM activity_events WHERE seller_id=? AND event_type='deal_closed'",
        [seller_id],
    )
    sf_updates = qn(
        "SELECT COUNT(*) FROM activity_events WHERE seller_id=? AND event_type='crm_update'",
        [seller_id],
    )

    # Source 2: Slack Events — peer recognitions (real-time collaboration signal)
    slack_recognitions = qn(
        "SELECT COUNT(*) FROM activity_events "
        "WHERE seller_id=? AND event_type IN ('peer_recognition', 'mentorship_session')",
        [seller_id],
    )

    # Source 3: Databricks historical metric — deal velocity in last 90 days
    # When B4 is real, Trino federates this to Databricks Delta in place.
    # When running against local DuckDB (test/dev), the synthetic data serves
    # as the representative historical signal.
    deal_velocity_90d = qn(
        "SELECT COUNT(*) FROM activity_events "
        "WHERE seller_id=? AND event_type='deal_closed' "
        "AND event_ts >= (now() - INTERVAL '90 days')",
        [seller_id],
    )

    # Seller display name
    name_row = q(
        "SELECT display_name, tenure_team_months, persona_label FROM sellers WHERE seller_id=?",
        [seller_id],
    )
    display_name  = name_row[0] if name_row else seller_id
    tenure_months = name_row[1] if name_row else 0
    persona_label = name_row[2] if name_row else ""

    return {
        "seller_id":         seller_id,
        "display_name":      display_name,
        "persona_label":     persona_label,
        "tenure_months":     tenure_months,
        # Source 1 — Salesforce CDC
        "sf_deals_closed":   sf_deals,
        "sf_crm_updates":    sf_updates,
        "_source_1":         "Salesforce CDC (live → Cassandra/Iceberg via B2)",
        # Source 2 — Slack Events
        "slack_recognitions": slack_recognitions,
        "_source_2":          "Slack Events (real-time → Cassandra/Iceberg via B2)",
        # Source 3 — Databricks historical metric (federated in place via B4)
        "db_deal_velocity_90d": deal_velocity_90d,
        "_source_3":            "Databricks Delta (historical — query-in-place via B4)",
    }


