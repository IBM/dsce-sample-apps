import React, { useState } from 'react';

// Anomaly injector. Rendered ONLY when the bridge runs with STREAM_MODE=mock.
// It drives POST /api/demo/load-data and /api/demo/reset-data, which do not
// exist in realtime mode (they return 404 there).

export function SimulatedBadge({ style }) {
  return (
    <span
      title="STREAM_MODE=mock: values are generated by the demo scenario engine, not read from Instana."
      style={{
        fontSize: 10, fontWeight: 700, letterSpacing: '0.05em', padding: '2px 8px', borderRadius: 10,
        color: '#161616', background: '#f1c21b', whiteSpace: 'nowrap', ...style,
      }}
    >
      MOCK DATA
    </span>
  );
}

export default function ScenarioControl({ scenarios, activeScenarioId, onSelect, onReset }) {
  const [open, setOpen] = useState(false);
  const active = scenarios.find((s) => s.id === activeScenarioId) || null;

  return (
    <div style={{ position: 'relative', display: 'inline-flex', alignItems: 'center', gap: 8, flexWrap: 'wrap' }}>
      <button
        type="button"
        aria-haspopup="listbox"
        aria-expanded={open}
        onClick={() => setOpen((o) => !o)}
        style={{
          padding: '5px 12px', borderRadius: 4, cursor: 'pointer', fontSize: 12, fontFamily: 'inherit',
          border: '1px solid #0f62fe', background: 'rgba(15,98,254,0.12)', color: '#78a9ff', fontWeight: 600,
        }}
      >
        🧪 Select SRE Anomaly Scenario ▾
      </button>

      {open && (
        <div role="listbox" aria-label="Anomaly scenarios" style={{
          position: 'absolute', top: '100%', left: 0, zIndex: 50, marginTop: 4, width: 380,
          background: 'var(--cds-layer-01)', border: '1px solid var(--cds-border-subtle-01)',
          borderRadius: 4, boxShadow: '0 4px 16px rgba(0,0,0,0.5)', maxHeight: 420, overflowY: 'auto',
        }}>
          {scenarios.length === 0 && (
            <div style={{ padding: 12, fontSize: 12, color: 'var(--cds-text-secondary)' }}>No scenarios available.</div>
          )}
          {scenarios.map((s) => {
            const sel = s.id === activeScenarioId;
            return (
              <button
                key={s.id}
                type="button"
                role="option"
                aria-selected={sel}
                onClick={() => { setOpen(false); onSelect(s.id); }}
                style={{
                  display: 'block', width: '100%', textAlign: 'left', padding: '10px 12px', cursor: 'pointer',
                  border: 'none', borderBottom: '1px solid var(--cds-border-subtle-01)', fontFamily: 'inherit',
                  background: sel ? 'rgba(15,98,254,0.15)' : 'transparent', color: 'var(--cds-text-primary)',
                }}
              >
                <div style={{ fontSize: 12, fontWeight: 600 }}>{s.icon} {s.shortName}{sel ? ' · ACTIVE' : ''}</div>
                <div style={{ fontSize: 11, color: 'var(--cds-text-secondary)', marginTop: 2 }}>{s.description}</div>
              </button>
            );
          })}
        </div>
      )}

      {active ? (
        <span style={{ fontSize: 11, fontWeight: 700, color: '#fa4d56' }}>🔴 {active.shortName} ACTIVE</span>
      ) : (
        <span style={{ fontSize: 11, fontWeight: 700, color: '#42be65' }}>✅ HEALTHY BASELINE</span>
      )}

      <button
        type="button"
        onClick={onReset}
        disabled={!active}
        style={{
          padding: '5px 12px', borderRadius: 4, fontSize: 12, fontFamily: 'inherit',
          cursor: active ? 'pointer' : 'not-allowed',
          border: '1px solid var(--cds-border-subtle-01)', background: 'var(--cds-layer-02)',
          color: active ? 'var(--cds-text-primary)' : 'var(--cds-text-placeholder)',
        }}
      >
        ↺ Reset Baseline
      </button>
    </div>
  );
}
